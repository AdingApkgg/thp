"""Derive each title's no-op opcode set from its own executable and generate the port's per-title table.

    py -3 tools/th-noop-opcodes.py            # write docs/porting/noop-opcodes.json and the header
    py -3 tools/th-noop-opcodes.py --check    # regenerate in memory and fail if either file is stale

An opcode does nothing in a title when either

  * it is outside the range the dispatch guard admits, because the guard's failure branch is itself a no-op in all
    six titles (a return-zero epilogue in TH12 and TH14, the script-pointer advance in TH13, TH16, TH17 and TH18), or
  * it is inside the range and the group table sends it to a handler whose body only returns or advances the script
    pointer.

Both are read from the executable rather than listed by hand: the classification is the same one the body audit uses,
applied to every permitted opcode instead of only the ones a single title's data happens to use. TH12 is the control
case, because its set was already derived a different way - by disassembling the dispatcher and recording which
opcodes reach its epilogue - and the existing table records 193 of them. This tool's TH12 set has to equal that
number and that set, which is what makes the other five something better than an assumption.
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

import capstone

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HANDLERS = HERE / "th-opcode-handlers.py"
AUDIT = HERE / "th-opcode-body-audit.py"
CASE_BODIES = ROOT / "docs/th12/ecl-case-bodies.json"
OUT_JSON = ROOT / "docs/porting/noop-opcodes.json"
OUT_HEADER = ROOT / "runtimes/th12/th12_web/cpp/game/NoopOpcodes.hpp"
TITLES = ("th12", "th13", "th14", "th16", "th17", "th18")
# The header's function takes the title as an integer so the port can select it from one constant.
NUMBERS = {"th12": 12, "th13": 13, "th14": 14, "th16": 16, "th17": 17, "th18": 18}


def load(name):
    path = HERE / name
    spec = importlib.util.spec_from_file_location(path.stem.replace("-", "_"), path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def table_derived(audit, handlers, title, image, base, sects, disassembler):
    """The no-op set read straight off the dispatch tables instead of the handler bodies.

    The group table holds one byte per permitted opcode and the jump table holds one target per group byte, so the
    handler an opcode reaches is `jump[group[op - first]]`. An opcode is a no-op when that target is the address the
    guard's failure branch goes to, because that is where the compiler put the shared no-op: TH12's epilogue at
    0x41962b, or the script-pointer advance TH13 to TH18 share. This is derived from the tables and the guard alone,
    so it is independent of the body classification - and TH12's own recorded set of 193 was produced this way.
    """
    entry = handlers.TITLES[title]
    jump, group, first = entry["jump"], entry["group"], entry["first"]
    bound = entry["bound"]
    target = audit.guard_fail(image, base, sects, group, bound, jump, disassembler)
    jump_bytes = audit.body(image, base, sects, jump, jump + 4 * (bound + 1))
    group_bytes = audit.body(image, base, sects, group, group + bound + 1)
    noops = set()
    for index in range(bound + 1):
        slot = group_bytes[index]
        address = int.from_bytes(jump_bytes[slot * 4:slot * 4 + 4], "little")
        if address == target:
            noops.add(first + index)
    return noops


def measure(audit, handlers):
    out = {}
    for title in TITLES:
        data = audit.handler_map(title)
        first = int(data["firstOpcode"], 16)
        last = int(data["lastOpcode"], 16)
        executable = handlers.TITLES[title]["exe"]
        image = Path(executable).read_bytes()
        base, sects = audit.sections(image)
        disassembler = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
        noops, bodies = set(), set()
        for address, entry in data["handlers"].items():
            if int(address, 16) == 0:
                continue
            ops = {int(o, 16) for o in entry["opcodes"]}
            if audit.is_noop(image, base, sects, int(address, 16), disassembler):
                noops |= ops
            else:
                bodies |= ops
        in_range = {op for op in noops | bodies if first <= op <= last}
        table = table_derived(audit, handlers, title, image, base, sects, disassembler)
        table = {op for op in table if first <= op <= last}
        out[title] = {"first": first, "last": last, "noops": sorted(noops), "bodies": sorted(bodies),
                      "executable": executable, "inRange": sorted(in_range), "tableNoops": sorted(table)}
    return out


def render_header(measured):
    lines = [
        "// Generated by tools/th-noop-opcodes.py from the six executables in tools/th-opcode-handlers.py - do not edit.",
        "//",
        "// Which opcodes do nothing, per title. An opcode does nothing when the dispatch guard rejects it - every",
        "// title's guard failure branch is itself a no-op, measured in tools/th-opcode-body-audit.py - or when the",
        "// group table hands it to a handler whose body only returns or advances the script pointer.",
        "//",
        "// TH12's column is the control: its set was first derived by disassembling the dispatcher and recording the",
        "// opcodes that reach its epilogue at 0x41962b, and that record holds 193 of them. This table reproduces the",
        "// same 193 by classifying handler bodies instead, so the other five columns rest on a classification that",
        "// has been checked against an independent derivation.",
        "//",
        "// The tables have to be per title. A shared codebase answers an opcode number the same way everywhere, so an",
        "// opcode TH12 dispatches to a body but TH13 skips would make the port act where the original does nothing.",
        "//",
        "// Above the top of each range every opcode is a no-op, which is why the predicates return true past `last`.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace {",
    ]
    for title in TITLES:
        row = measured[title]
        span = row["last"] - row["first"] + 1
        bits = bytearray((span + 7) // 8)
        for op in row["noops"]:
            index = op - row["first"]
            bits[index >> 3] |= 1 << (index & 7)
        body = ",\n".join("        " + ",".join("0x%02x" % b for b in bits[i:i + 16]) for i in range(0, len(bits), 16))
        lines.append("// %s: %d no-op opcodes in 0x%x..0x%x (%d permitted)"
                     % (title, len(row["noops"]), row["first"], row["last"], span))
        lines.append("const uint8_t %s_bits[]={" % title)
        lines.append(body + ",")
        lines.append("};")
        lines.append("const uint16_t %s_first=0x%x,%s_last=0x%x;" % (title, row["first"], title, row["last"]))
    lines.append("}")
    lines.append("")
    lines.append("// Deliberately at global scope: EnemyCommands.cpp nests its namespaces (th11::th11), so a declaration")
    lines.append("// inside namespace th11 would not be found by unqualified lookup from there. title_noop_opcode takes the")
    lines.append("// title number so one build can be checked against every other title's table; runtime_noop_opcode is the")
    lines.append("// one the handlers call and follows kPortTitle from PortTitle.hpp.")
    lines.append("inline bool title_noop_opcode(uint32_t title,uint16_t opcode)noexcept{")
    lines.append("    const uint8_t* bits=nullptr;uint32_t first=0,last=0;")
    lines.append("    switch(title){")
    for title in TITLES:
        lines.append("    case %d:bits=%s_bits;first=%s_first;last=%s_last;break;"
                     % (NUMBERS[title], title, title, title))
    lines.append("    default:return false;")
    lines.append("    }")
    lines.append("    if(opcode>last)return true;")
    lines.append("    if(opcode<first)return false;")
    lines.append("    const uint32_t index=uint32_t(opcode)-first;")
    lines.append("    return ((bits[index>>3]>>(index&7))&1)!=0;")
    lines.append("}")
    lines.append("")
    lines.append("#include \"PortTitle.hpp\"")
    lines.append("inline bool runtime_noop_opcode(uint16_t opcode)noexcept{return title_noop_opcode(kPortTitle,opcode);}")
    lines.append("")
    return "\n".join(lines)


def render_json(measured):
    return {
        "source": "handler bodies disassembled from each title's executable by tools/th-noop-opcodes.py",
        "titles": {title: {"first": "0x%x" % measured[title]["first"], "last": "0x%x" % measured[title]["last"],
                           "noopCount": len(measured[title]["noops"]),
                           "bodyCount": len(measured[title]["bodies"]),
                           "noops": ["0x%x" % op for op in measured[title]["noops"]],
                           "executable": measured[title]["executable"]}
                   for title in TITLES},
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    audit = load("th-opcode-body-audit.py")
    handlers = load("th-opcode-handlers.py")
    measured = measure(audit, handlers)

    # Both derivations, for every title: the handler-body classification and the dispatch-table reading. They are
    # independent - one walks function bodies, the other reads two tables and the guard's failure address - so an
    # agreement is evidence and a disagreement is a defect in this tool or in the tables, not something to average.
    for title in TITLES:
        row = measured[title]
        body_set = set(row["inRange"]), set(row["noops"]) & set(row["inRange"])
        in_range, body_noops = body_set
        table_noops = set(row["tableNoops"])
        if body_noops != table_noops:
            print("  FAIL %s: the body classification says %d in-range no-ops, the dispatch tables say %d; "
                  "%d body-only %s, %d table-only %s"
                  % (title, len(body_noops), len(table_noops), len(body_noops - table_noops),
                     " ".join(hex(o) for o in sorted(body_noops - table_noops)[:8]),
                     len(table_noops - body_noops),
                     " ".join(hex(o) for o in sorted(table_noops - body_noops)[:8])))
            sys.exit(1)
        row["noops"] = sorted(body_noops)
        row["bodies"] = sorted(in_range - body_noops)

    # The control: TH12's set has to be the one the dispatcher-derived record holds, not merely the same size.
    recorded = {int(op) for op in json.loads(CASE_BODIES.read_text(encoding="utf-8"))["noops"]}
    derived = set(measured["th12"]["noops"])
    if recorded != derived:
        only_recorded = sorted(recorded - derived)
        only_derived = sorted(derived - recorded)
        print("  FAIL th12 histogram differs from docs/th12/ecl-case-bodies.json: %d recorded-only %s, %d derived-only %s"
              % (len(only_recorded), " ".join(hex(o) for o in only_recorded[:8]),
                 len(only_derived), " ".join(hex(o) for o in only_derived[:8])))
        sys.exit(1)

    header = render_header(measured)
    document = json.dumps(render_json(measured), indent=1, sort_keys=True) + "\n"

    # The hazard this table exists for: an opcode the port has a case for, in a title whose original skips it. The
    # port consults runtime_noop_opcode before any handler, so such a case is unreachable in that title - and that is
    # a property of the table, so it can be checked here rather than asserted. The set is reported because it is what
    # would otherwise have made the port act where the original does nothing.
    mentions = load("th-opcode-coverage.py").port_mentions()
    guarded = {}
    for title in TITLES:
        row = measured[title]
        noops = set(row["noops"])
        hazard = sorted(op for op in range(row["first"], row["last"] + 1) if op in noops and op in mentions)
        unreachable = [op for op in hazard if op not in noops]
        if unreachable:
            print("  FAIL %s: %d named opcodes are unreachable but not in the no-op table: %s"
                  % (title, len(unreachable), " ".join(hex(o) for o in unreachable[:8])))
            sys.exit(1)
        guarded[title] = hazard

    if args.check:
        bad = 0
        if not OUT_HEADER.exists() or OUT_HEADER.read_text(encoding="utf-8") != header:
            print("  FAIL %s is stale - rerun tools/th-noop-opcodes.py" % OUT_HEADER.relative_to(ROOT))
            bad += 1
        if not OUT_JSON.exists() or OUT_JSON.read_text(encoding="utf-8") != document:
            print("  FAIL %s is stale - rerun tools/th-noop-opcodes.py" % OUT_JSON.relative_to(ROOT))
            bad += 1
        for title in TITLES:
            row = measured[title]
            print("  %s 0x%x..0x%x: %d permitted, %d no-op, %d with a body; %d named opcodes are skipped here and "
                  "therefore unreachable"
                  % (title, row["first"], row["last"], len(row["noops"]) + len(row["bodies"]),
                     len(row["noops"]), len(row["bodies"]), len(guarded[title])))
        print("  th12 no-op set equals the dispatcher-derived record (%d opcodes)" % len(recorded))
        sys.exit(1 if bad else 0)
    OUT_HEADER.write_text(header, encoding="utf-8", newline="\n")
    OUT_JSON.write_text(document, encoding="utf-8", newline="\n")
    print("  wrote %s" % OUT_HEADER.relative_to(ROOT))
    print("  wrote %s" % OUT_JSON.relative_to(ROOT))


if __name__ == "__main__":
    main()
