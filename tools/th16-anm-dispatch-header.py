"""Generate TH16 ANM no-op classification from the pinned retail dispatcher."""
import hashlib, importlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
img,table,default=importlib.import_module('th-anm-handlers').handlers(16)
last=max(table)
bits=[0]*((last+8)//8)
for op,entry in table.items():
    if op>=0 and entry!=default:bits[op//8]|=1<<(op%8)
digest=hashlib.sha256(img.data).hexdigest()
text='// Generated by tools/th16-anm-dispatch-header.py from pinned retail TH16.\n'
text+=f'// Executable SHA256 {digest}; default handler {default:#x}.\n#pragma once\n#include "Types.hpp"\nnamespace th11 {{\n'
text+='inline constexpr u8 th16_anm_real_bits[]={\n'
for i in range(0,len(bits),16):text+='    '+','.join(f'0x{b:02x}' for b in bits[i:i+16])+',\n'
text+='};\n'
text+=f'inline bool th16_anm_native_noop(u16 op) noexcept{{return op>{last}||!(th16_anm_real_bits[op/8]&(1u<<(op%8)));}}\n}}\n'
path=ROOT/'runtimes/th12/th12_web/cpp/game/Th16AnmDispatch.hpp'
path.write_text(text,encoding='utf-8')
record=dict(title=16,domain='ANM',executableSha256=digest,defaultHandler=hex(default),last=last,entries=len(table),realHandlers=len({v for v in table.values() if v!=default}),noops=[op for op in range(last+1) if table.get(op,default)==default],source='runtimes/th12/th12_web/cpp/game/Th16AnmDispatch.hpp',sourceSha256=hashlib.sha256(path.read_bytes()).hexdigest())
(ROOT/'docs/porting/th16-anm-noop-classification.json').write_text(json.dumps(record,indent=2)+'\n',encoding='utf-8')
print(f'TH16 ANM: {len(table)} entries, {len(record["noops"])} native no-ops')
