// Generate the th12 "no-op opcode" table for the port from the case-body artifact.
//
// FUN_004154d0 dispatches through two tables (byte table 0x419890, jump table 0x419654). Opcodes whose
// entry points at 0x41962b reach the function's epilogue, which is `xor eax,eax` plus the SEH unwind -
// it does nothing and reports success. The port inherited TH11 handlers that act on some of those
// opcodes anyway, which is the same "live shadow" that made 0x118 get removed from the movement
// switch. This turns the authoritative list into a bitmap the port can consult.
//
// Docs and evidence: docs/th12/oracle-repointing.md §17, docs/th12/ecl-case-bodies.json.
//   node tools/th12-noop-opcodes.mjs           # write the header
//   node tools/th12-noop-opcodes.mjs --check   # fail if the header drifted
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(root, 'docs/th12/ecl-case-bodies.json');
const OUT = resolve(root, 'runtimes/th12/th12_web/cpp/game/Th12NoopOpcodes.hpp');
const LO = 0x100, HI = 0x263;

const artifact = JSON.parse(readFileSync(SOURCE, 'utf8'));
const noops = [...new Set((artifact.noops ?? []).map(Number))].filter(op => op >= LO && op <= HI).sort((a, b) => a - b);
if (noops.length === 0) throw Error(`${SOURCE} has no noop list to generate from`);

// One bit per opcode over LO..HI, so the lookup needs no search and no relocatable table of pointers.
const bitmap = new Uint8Array(Math.ceil((HI - LO + 1) / 8));
for (const op of noops) {
  const index = op - LO;
  bitmap[index >> 3] |= 1 << (index & 7);
}
const bytes = [...bitmap].map(b => '0x' + b.toString(16).padStart(2, '0')).join(',');
const wrapped = [];
for (let i = 0; i < bytes.length; i += 100) wrapped.push('    ' + bytes.slice(i, i + 100).replace(/,$/, ''));
const body = wrapped.join(',\n');

const generated = `// Generated by tools/th12-noop-opcodes.mjs from docs/th12/ecl-case-bodies.json - do not edit.
//
// The ${noops.length} opcodes in 0x${LO.toString(16)}..0x${HI.toString(16)} that FUN_004154d0 routes to its
// epilogue at 0x41962b. The epilogue is \`xor eax,eax\` followed by the SEH unwind and \`ret\`, so these
// instructions do nothing and report success. A port handler that acts on one of them diverges from
// the original even though it returns the same value.
//
// The guard itself is what makes the range above HI a no-op rather than merely unrouted:
//
//   0x0041551e  movzx eax, word ptr [edi + 4]     the command opcode
//   0x00415525  add   ecx, 0xffffff00
//   0x00415533  cmp   ecx, 0x163
//   0x00415539  ja    0x41962b                     the same epilogue
//
// so any opcode at or above LO that the table does not reach takes the epilogue. Reporting those as
// "not a no-op" would run a handler the original never runs, which is exactly the divergence this
// table exists to prevent. Below LO the value is not a command at all: it is one of the interpreter's
// own operations, dispatched before the command layer.
#pragma once
#include <cstdint>
// Deliberately at global scope. EnemyCommands.cpp nests its namespaces (th11::th11), so a declaration
// inside namespace th11 would not be found by unqualified lookup from there, while a global one is
// visible from every translation unit that includes this header.
inline bool th12_noop_opcode(uint16_t opcode)noexcept{
    static const uint8_t bits[]={
${body},
    };
    if(opcode<0x${LO.toString(16)})return false;
    if(opcode>0x${HI.toString(16)})return true;
    const unsigned index=opcode-0x${LO.toString(16)};
    return ((bits[index>>3]>>(index&7))&1)!=0;
}
`;

if (process.argv.includes('--check')) {
  // The header's own predicate, re-derived here so the boundary behaviour is asserted rather than assumed. A check
  // that only compared bytes to bytes would still pass on the version this replaced, where an opcode past the
  // table reported "not a no-op" and a handler the original never runs would be reached.
  const inTable = op => op >= LO && op <= HI && noops.includes(op);
  const predicate = op => (op < LO ? false : op > HI ? true : inTable(op));
  const boundary = [
    [0x0ff, false, 'below the command range: an interpreter operation, not a command'],
    [0x100, predicate(0x100), 'the first command id'],
    [0x263, predicate(0x263), 'the last id the table reaches'],
    [0x264, true, 'one past the table: the guard jumps to the epilogue'],
    [0x2bc, true, 'used by the shipped th12 scripts and outside the table'],
  ];
  for (const [op, want, why] of boundary) {
    if (predicate(op) !== want) {
      console.error(`no-op boundary wrong at ${op.toString(16)}: want ${want} (${why})`);
      process.exit(1);
    }
  }
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== generated) {
    console.error('Th12NoopOpcodes.hpp is out of date - run node tools/th12-noop-opcodes.mjs');
    process.exit(1);
  }
  console.log(`Th12NoopOpcodes.hpp matches ${noops.length} no-op opcodes, and ${boundary.length} boundary cases hold`);
} else {
  writeFileSync(OUT, generated);
  console.log(`wrote ${OUT}`);
  console.log(`  ${noops.length} no-op opcodes in 0x${LO.toString(16)}..0x${HI.toString(16)}`);
  console.log(`  first: ${noops.slice(0, 10).map(o => '0x' + o.toString(16)).join(' ')}`);
  console.log(`  last:  ${noops.slice(-6).map(o => '0x' + o.toString(16)).join(' ')}`);
}
