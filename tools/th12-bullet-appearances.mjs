#!/usr/bin/env node
// Generate runtimes/th12/th12_web/cpp/game/BulletAppearance.cpp from TH12's own
// bullet appearance table instead of the hand-reconstructed TH11 one.
//
// The table lives at DAT_004af280 in th12.exe with a stride of 0xd0 - which is
// exactly sizeof(BulletAppearance), and the fields line up with the port's struct:
// script at +0x00, sprites[48] at +0x04, hitbox at +0xc4, group at +0xc8,
// effect_mode at +0xcc. Eighteen decompiled functions index it as
// `&DAT_004af280 + sprite * 0xd0`, so the layout is not a guess.
//
// Reading it directly matters because the port's table was rebuilt from TH11's ANM
// layout and its script column does not match TH12's at all: TH11 starts {0,34,35},
// TH12 starts {35,36,37}, and TH12 has two types beyond TH11's 29. Stage 4 was
// failing in BulletManager::appearance because a bullet's type index ran past the
// shorter array.
//
// Usage:
//   node tools/th12-bullet-appearances.mjs            regenerate the C++ source
//   node tools/th12-bullet-appearances.mjs --check    verify the committed source

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'runtimes', 'th12', 'th12_web', 'cpp', 'game', 'BulletAppearance.cpp');
const check = process.argv.includes('--check');

const exe = process.env.TH12_EXE ?? 'H:\\Games\\th\\12\\th12.exe';
if (!fs.existsSync(exe)) {
    console.error(`th12.exe not found: ${exe} (set TH12_EXE to override)`);
    process.exit(1);
}

const STORAGE = 0xac000 + (0x4af280 - 0x4ad000);
const STRIDE = 0xd0;
const SPRITES = 48;
const COUNT = 31;   // entries 0..30; entry 31 onward is unrelated data

const bytes = fs.readFileSync(exe);

// The eight cancel-effect scripts mode 1 indexes. These used to be written into the source by hand, and
// the hand-written set was TH11's: TH12 raised every one of them by two. BulletManager::appearance gets
// them from the original's DAT_004b0bb0, which is the table mode 1's jump-table target at 0x40ae1f reads
// with `mov eax,[edx*4 + 0x4b0bb0]`, so read the same table rather than restating it.
const CANCEL = 0xac000 + (0x4b0bb0 - 0x4ad000);
const cancel_scripts = Array.from({length: 8}, (_, i) => bytes.readInt32LE(CANCEL + i * 4));
if (!cancel_scripts.every((s) => s > 0 && s < 0x1000) || cancel_scripts.length !== 8) {
    console.error(`refusing to write: cancel script column looks wrong: ${cancel_scripts.join(',')}`);
    process.exit(1);
}
const entries = [];
for (let i = 0; i < COUNT; i++) {
    const base = STORAGE + i * STRIDE;
    entries.push({
        script: bytes.readInt32LE(base),
        sprites: Array.from({length: SPRITES}, (_, n) => bytes.readInt32LE(base + 4 + n * 4)),
        hitbox: bytes.readFloatLE(base + 0xc4),
        group: bytes.readInt32LE(base + 0xc8),
        effect: bytes.readInt32LE(base + 0xcc),
    });
}

// A cheap guard against the stride or base being wrong: if the layout were off,
// these columns would be noise rather than the small coherent values TH12 has.
const scripts = entries.map((e) => e.script);
if (!scripts.every((s) => s > 0 && s < 0x1000)) {
    console.error(`refusing to write: script column looks wrong: ${scripts.join(',')}`);
    process.exit(1);
}
if (!entries.every((e) => e.hitbox >= 0 && e.hitbox <= 64 && e.effect >= 0 && e.effect <= 8)) {
    console.error('refusing to write: hitbox or effect_mode column out of range');
    process.exit(1);
}

const f = (v) => (Number.isInteger(v) ? `${v}.0f` : `${v}f`);
const row = (values, per, pad) => {
    const lines = [];
    for (let i = 0; i < values.length; i += per) {
        lines.push('        ' + values.slice(i, i + per).map((v) => String(v).padStart(pad)).join(',') + ',');
    }
    return lines.join('\n');
};

const source = `#include "BulletAppearance.hpp"
namespace th11 {
// TH12's bullet appearance table, read from th12.exe DAT_004af280 (stride 0xd0).
// Generated by tools/th12-bullet-appearances.mjs - edit that, not this file.
// The TH11-derived table this replaced had a different script column ({0,34,35,...}
// against TH12's {35,36,37,...}) and only 29 entries, which made stage 4 fail in
// BulletManager::appearance once it fired a type index past the end.
const std::array<i32,8> bullet_cancel_scripts={${cancel_scripts.join(',')}};
namespace {
constexpr std::array<BulletAppearance,${COUNT}> appearances(){
    constexpr i32 scripts[${COUNT}]={
${row(scripts, 10, 4)}
    };
    constexpr float hitboxes[${COUNT}]={
${row(entries.map((e) => f(e.hitbox)), 8, 5)}
    };
    constexpr i32 groups[${COUNT}]={
${row(entries.map((e) => e.group), 12, 2)}
    };
    constexpr i32 effects[${COUNT}]={
${row(entries.map((e) => e.effect), 12, 2)}
    };
    constexpr i32 sprites[${COUNT}][${SPRITES}]={
${entries.map((e, i) => `        {   // type ${i}, script ${e.script}\n${row(e.sprites, 16, 5)}\n        },`).join('\n')}
    };
    std::array<BulletAppearance,${COUNT}> result{};
    for(i32 type=0;type<${COUNT};++type){auto& a=result[type];a.script=scripts[type];a.hitbox=hitboxes[type];a.group=groups[type];a.effect_mode=effects[type];
        for(i32 n=0;n<${SPRITES};++n)a.sprites[n]=sprites[type][n];
    }return result;
}
}
const std::array<BulletAppearance,${COUNT}> bullet_appearances=appearances();
}
`;

if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== source) {
        console.error(`${OUT} is stale - rerun the generator`);
        process.exit(1);
    }
    console.log(`bullet appearance table up to date: ${COUNT} entries`);
    process.exit(0);
}

fs.writeFileSync(OUT, source);
console.log(`wrote ${OUT}`);
console.log(`  entries ${COUNT}, stride 0x${STRIDE.toString(16)}, from ${exe}`);
console.log(`  scripts: ${scripts.join(',')}`);
