#!/usr/bin/env python3
"""Measure, per title, how many of the opcodes its shipped scripts use the port accounts for at all.

This is a coverage question, not a correctness one: it asks whether an opcode is named anywhere in the port's
game half. It is the cheapest way to turn "this title is not ported" into a list, and it cross-checks the guard
work from the other direction - an opcode that both falls outside a title's guard and is absent from the sources is
a gap two independent measurements agree on, not one tool's opinion.

    py -3 tools/th-opcode-coverage.py --check
"""
import argparse
import glob
import re
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PORT = REPO / "runtimes/th12/th12_web/cpp/game"
DATA = {
    "12": "runtimes/th12/th12_web/artifacts/cpp/th12-data",
    "13": "runtimes/th13/th13_web/artifacts/cpp/th13-data",
    "14": "runtimes/th14/th14_web/artifacts/cpp/th14-data",
    "16": "runtimes/th16/th16_web/artifacts/cpp/th16-data",
    "17": "runtimes/th17/th17_web/artifacts/cpp/th17-data",
    "18": "runtimes/th18/th18_web/artifacts/cpp/th18-data",
}

# Measured with this tool. `case` counts opcodes the port has a case label for; `noCase` is the rest, and it includes
# the interpreter's core opcodes, which the port routes by interval rather than by case label (see the note in
# EnemyScript.cpp about 0x100..0x10f and 0x118). So `noCase` is an upper bound on what is missing, while `mentioned`
# below is what the earlier version of this file counted - 272 constants, of which many are only discussed in comments.
RECORDED = {
    "12": {"used": 157, "high": 112, "case": 107, "noCase": 5},
    "13": {"used": 177, "high": 129, "case": 62, "noCase": 67},
    "14": {"used": 176, "high": 131, "case": 64, "noCase": 67},
    "16": {"used": 177, "high": 131, "case": 65, "noCase": 66},
    "17": {"used": 154, "high": 107, "case": 55, "noCase": 52},
    "18": {"used": 164, "high": 118, "case": 60, "noCase": 58},
}

# The opcodes th12's data uses that the sources never name. Kept so a route added for one of them shows up here.
# 0x117 left this list when its body was transcribed from the handler at 0x415c93. 0x2bc stays even though the
# machine's guard proves it a no-op: the generated no-op table handles it, but no source names it. 0x20d left it
# when the emitter-origin setter was transcribed from 0x417fab and compared against the original by the
# emitter-origin test.
# The opcodes the port has neither a case label nor an equality test for. This was 27 before the tool learned to count
# `if (op == 0x...)`, and the correction is instructive: the core opcodes 0x101..0x118, and 0x1a0 and 0x1f5, are all
# claimed through the routing condition or through enemy_fire_command's opening test, none of them had a case label.
# What is left is the real list. 0x2bc is not an opcode: it is a value in the data above the dispatch range, and the
# guard rejects it as a no-op in the original too, so the per-opcode gaps are the first five.
TH12_NOCASE = [0x141, 0x25b, 0x260, 0x263, 0x2bc]


def port_cases():
    """The opcodes the port actually has a case for.

    A case label, not a mention. The earlier version of this tool counted any three-digit hex constant anywhere in the
    port's sources, comments included, and that turned out to overstate the port by a wide margin: TH12's 0x25c through
    0x262 appeared in comments describing what TH11 bodies used to do while no case existed for any of them, so the
    audit called five unimplemented opcodes "named" and reported two unresolved where the truth was seven. A case
    label cannot be written about without existing.
    """
    cases = set()
    for pattern in ("*.cpp", "*.hpp"):
        for path in sorted(PORT.glob(pattern)):
            source = path.read_text(encoding="utf-8", errors="replace")
            if "Generated by tools/" in source:
                continue
            for match in re.finditer(r"\bcase\s+(0x[0-9a-fA-F]+|\d+)\s*:", source):
                text = match.group(1)
                cases.add(int(text, 16) if text.lower().startswith("0x") else int(text))
    return cases


def port_exact_ops():
    """The opcodes the port claims with an equality test instead of a case label.

    `enemy_fire_command` opens with `if (opcode != 0x1f5) return -2`, so 0x1f5 is implemented while having no case
    label. This is why the case count is a lower bound; the tool reports both so the gap list is a subtraction the
    reader can follow, rather than one number that is wrong in a different direction than the previous one.
    """
    ops = set()
    for pattern in ("*.cpp", "*.hpp"):
        for path in sorted(PORT.glob(pattern)):
            source = path.read_text(encoding="utf-8", errors="replace")
            if "Generated by tools/" in source:
                continue
            for match in re.finditer(r"\b(?:op|opcode)\s*[!=]=\s*(0x[0-9a-fA-F]{3,5}|\d{3,5})\b", source):
                text = match.group(1)
                ops.add(int(text, 16) if text.lower().startswith("0x") else int(text))
    return ops


def port_mentions():
    text = ""
    for pattern in ("*.cpp", "*.hpp"):
        for path in sorted(PORT.glob(pattern)):
            source = path.read_text(encoding="utf-8", errors="replace")
            # Generated tables are not claims to handle an opcode. The no-op bitmap lists ranges like
            # 0x12d..0x1fc in its comments and would otherwise register every boundary as a mention, which moved the
            # per-title named and unnamed counts without a single handler changing.
            if "Generated by tools/" in source[:400] or "Generated by tools/" in source:
                continue
            text += source
    return set(int(m, 16) for m in re.findall(r"0x([0-9a-fA-F]{3})\b", text))


def used(title, directory):
    ops = set()
    for path in sorted(glob.glob(str(Path(REPO) / directory / "*.ecl"))):
        blob = Path(path).read_bytes()
        if len(blob) < 36 or blob[:4] != b"SCPT":
            continue
        header = struct.unpack_from("<H", blob, 6)[0]
        count = struct.unpack_from("<H", blob, 16)[0]
        table = 36 + header
        if table + count * 4 > len(blob):
            continue
        for i in range(count):
            start = struct.unpack_from("<I", blob, table + i * 4)[0]
            if blob[start:start + 4] != b"ECLH":
                continue
            at = start + 16
            while at + 16 <= len(blob):
                opcode = struct.unpack_from("<H", blob, at + 4)[0]
                length = struct.unpack_from("<H", blob, at + 6)[0]
                if length < 16 or length % 4 or at + length > len(blob):
                    break
                ops.add(opcode)
                at += length
    return ops


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    mentioned = port_mentions()
    cases = port_cases() | port_exact_ops()
    print("  the port's game half mentions %d distinct three-digit constants and has %d distinct case labels" % (len(mentioned), len(cases)))
    bad = 0
    detail = {}
    for title in sorted(DATA, key=int):
        directory = DATA[title]
        if not (Path(REPO) / directory).is_dir():
            print("  th%-4s (no extracted resources)" % title)
            continue
        ops = used(title, directory)
        high = sorted(o for o in ops if o >= 0x100)
        named = [o for o in high if o in cases]
        missing = [o for o in high if o not in cases]
        spoken = [o for o in high if o in mentioned and o not in cases]
        detail[title] = missing
        print("  th%-4s used=%-4d high=%-4d case=%-4d no-case=%-4d (mentioned-only %d) %s"
              % (title, len(ops), len(high), len(named), len(missing), len(spoken),
                 ("  " + ", ".join("%#x" % o for o in missing[:6]) + (" ..." if len(missing) > 6 else "")) if missing else ""))
        want = RECORDED.get(title)
        if args.check and want is not None:
            measured = {"used": len(ops), "high": len(high), "case": len(named), "noCase": len(missing)}
            for key in want:
                if want[key] != measured[key]:
                    bad += 1
                    print("      FAIL %s %s recorded=%d measured=%d" % (title, key, want[key], measured[key]))
        if args.check and title == "12":
            if sorted(missing) != TH12_NOCASE:
                bad += 1
                print("      FAIL th12 no-case set changed: %s" % ", ".join("%#x" % o for o in sorted(missing)))
    if args.check:
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
