"""Recover TH14 sample/voice tables and check the compiled source data.

46d980 loads 65 sample names from 4d60b0; 46d660 / 46f160 resolve
76 voice IDs by the first field of the 20-byte rows at 4d61b8.
This verifies table identity and shipped WAV headers, not playback scheduling.
"""
import hashlib,importlib,json,re,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
image=importlib.import_module('th12-pe').Image('H:/Games/th/14/th14.exe')
sha=lambda b:hashlib.sha256(b).hexdigest()
names=[image.cstring(image.u32(0x4d60b0+n*4)) for n in range(65)]
rows=[struct.unpack('<iihhii',image.read(0x4d61b8+n*20,20)) for n in range(76)]
assert sorted(r[0] for r in rows)==list(range(76))
queue_metadata=[r[3] for r in rows]
rows.sort()
archive=json.loads((ROOT/'artifacts/archive-differential/th14.json').read_text(encoding='utf-8'))
data=Path(archive['extraction'])
samples=[]
for name in names:
    assert re.fullmatch(r'se_[a-z0-9_]+\.wav',name),name
    b=(data/name).read_bytes()
    assert b[:4]==b'RIFF' and b[8:12]==b'WAVE',name
    assert sha(b)==next(r['sha256'] for r in archive['decoded'] if r['name']==name)
    samples.append(dict(name=name,bytes=len(b),sha256=sha(b)))
assert all(0<=r[1]<65 for r in rows)
text='// Generated by tools/th14-audio-table.py from TH14 1.00b.\n'
text+='const SoundDefinition sound_definitions[sound_voice_count]={\n'
text+='\n'.join(' '+','.join('{%d,%d,%d,%d,%d}'%(r[1],r[2],r[3],r[4],queue_metadata[r[0]]) for r in rows[n:n+6])+',' for n in range(0,76,6))+'\n};\n'
text+='namespace {\nconst char* const th14_sound_samples[65]={\n'
text+='\n'.join(' '+','.join(json.dumps(s) for s in names[n:n+5])+',' for n in range(0,65,5))+'\n};\n}\n'
destination=ROOT/'runtimes/th12/th12_web/cpp/game/Th14AudioTables.inc'
if '--write' in sys.argv:destination.write_text(text,encoding='utf-8')
assert destination.read_text(encoding='utf-8')==text,'regenerate with --write'
report=dict(passed=True,executableSha256=sha(image.data),sampleTable='0x4d60b0',voiceTable='0x4d61b8',
            samples=samples,voices=[dict(id=r[0],sample=r[1],volume=r[2],metadata=r[3],loop=r[4],positional=r[5],queueMetadata=queue_metadata[r[0]]) for r in rows],
            scope='Sample names and voice ID/sample/volume/metadata/play flags, plus archive WAV hashes. Native positional flags are recorded; playback scheduling/device output require separate proof.',
            generatedSha256=sha(text.encode()),toolSha256=sha(Path(__file__).read_bytes()))
(ROOT/'docs/porting/th14-audio-table-verified.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print('PASS: 65 native TH14 samples and 76 voice IDs; all shipped WAV hashes match.')
