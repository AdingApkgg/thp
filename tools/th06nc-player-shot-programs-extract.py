"""Extract the original four shot tables (nine power bands, 36-byte records)."""
import hashlib,json,struct
from th06nc_native import Native,ROOT

def main():
    n=Native();m=n.m;programs=[];digest=hashlib.sha256()
    for pointer in [0x1403dcdb0,0x1403dd530,0x1403dcbd0,0x1403dc8a0]:
        rows=[]
        for row in range(9):
            count,threshold,address=struct.unpack('<iiQ',m.mem_read(pointer+row*16,16));assert 1<=count<=12;assert 0<threshold<=999;raw=bytes(m.mem_read(address,count*36));digest.update(raw);rows.append(dict(powerBelow=threshold,records=[raw[i*36:(i+1)*36].hex()for i in range(count)]))
        assert [r['powerBelow']for r in rows]==[8,16,32,48,64,80,96,128,999];programs.append(rows)
    source='shared/th06nc/player-shot-programs.mjs';(ROOT/source).write_text('// Original executable shot table records; generated by tools/th06nc-player-shot-programs-extract.py.\nexport const playerShotPrograms='+json.dumps(programs,separators=(',',':'))+';\n',encoding='utf-8')
    report=dict(scope=__doc__,profiles=4,powerBands=36,records=sum(len(r['records'])for p in programs for r in p),dataSha256=digest.hexdigest(),sourceSha256={source:hashlib.sha256((ROOT/source).read_bytes()).hexdigest()},executableSha256=n.target['sha256'],passed=True,completeGame=False,nativeEquivalent=False)
    (ROOT/'docs/porting/th06nc-player-shot-programs-extracted.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
if __name__=='__main__':main()
