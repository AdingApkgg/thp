"""Write the canonical per-function disassembly the transcription method works from.

The scene-schedule suite reads th11 functions as text and parses them with three uppercase patterns:

    MOV EBX,0x...
    MOV dword ptr [EAX|ESI + 0x8],0x...
    CALL 0x00456c10

so the dump is not free-form: it is the worksheet the oracle reads, and its dialect is part of the
contract. Capstone emits lowercase with decimal displacements and a space after the comma, so the
formatter below restores exactly what those patterns expect, and every line carries the address and
the raw bytes so a transcription can be checked against the image byte for byte.

Bounds: a function ends at a `ret` whose following bytes are padding, or at the first padding
instruction after the body; 0x800 bytes is the ceiling, and the tool prints what it chose so the bound
is visible rather than implied.
"""
import io
import os
import re
import sys
from importlib.machinery import SourceFileLoader

FIND = SourceFileLoader('twinfind', 'tools/th-twin-find.py').load_module()
import capstone

MD = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
PADDING = {0xcc, 0x90, 0x00, 0xc3, 0xcb}
OUT = 'runtimes/th12/th12_web/artifacts/cpp/analysis/jp/functions'


REG = re.compile(r'\b(eax|ebx|ecx|edx|esi|edi|ebp|esp|eip|ax|bx|cx|dx|si|di|bp|sp|al|bl|cl|dl|ah|bh'
                 r'|ch|dh|fs|gs|cs|ds|es|ss|st0|st)\b')


def upper(insn):
    """The dump's dialect, which the suite's patterns define exactly.

    The mnemonic and the registers are uppercase; `dword ptr` stays lowercase; hex is `0x` with
    lowercase digits; a call or jump target is zero-padded to eight digits, because the pattern the
    suite matches is `CALL 0x00456c10`; and a bracket displacement is hex. The first version uppercased
    the whole line, so `0x` became `0X` and `CALL 0x456c10` stayed short - the dumps were generated and
    matched nothing.
    """
    text = '%s %s' % (insn.mnemonic, insn.op_str)
    head, _, tail = text.partition(' ')
    head = head.upper()
    tail = REG.sub(lambda m: m.group(1).upper(), tail)
    tail = re.sub(r'0x([0-9A-Fa-f]+)', lambda m: '0x' + m.group(1).lower(), tail)

    def bracket(match):
        inner = re.sub(r'(?<![\w])(\d+)(?![\w])', lambda m: '0x%x' % int(m.group(1)), match.group(1))
        return '[' + REG.sub(lambda m: m.group(1).upper(), inner) + ']'

    tail = re.sub(r'\[([^\]]*)\]', bracket, tail)
    if head in ('CALL', 'JMP'):
        tail = re.sub(r'0x([0-9a-f]+)', lambda m: '0x' + m.group(1).zfill(8), tail)
    return (head + ' ' + tail).strip().replace(', ', ',')


def function(md, start, blob, base, ceiling=0x800):
    offset, address, count, total = start - base, start, 0, 0
    lines = []
    while 0 <= offset < len(blob) and count < ceiling:
        decoded = list(md.disasm(blob[offset:offset + 16], address))
        if not decoded:
            break
        insn = decoded[0]
        raw = blob[offset:offset + insn.size]
        if count and raw[0] in (0xcc, 0x90) and insn.size == 1:
            break
        lines.append('%08x  %-18s %s' % (insn.address, raw.hex(), upper(insn)))
        count += 1
        total += insn.size
        offset += insn.size
        address += insn.size
        if insn.mnemonic in ('ret', 'retf') and count:
            tail = blob[offset:offset + 4]
            if not tail or all(byte in PADDING for byte in tail):
                break
    return lines, total


def main():
    args = sys.argv[1:]
    exe = args[args.index('--exe') + 1] if '--exe' in args else 'H:/Games/th/11/th11.exe'
    addresses = []
    if '--from-suite' in args:
        text = io.open(args[args.index('--from-suite') + 1], encoding='utf-8').read()
        # the suite names functions both in table rows (`['004526f0',`) and in literal paths
        # (`functions/004298c0.asm`), and a dump generator that reads only one of them leaves the other
        # failing on a missing file
        found = set()
        for match in re.findall(r"\['([0-9a-f]{8})'", text):
            found.add(int(match, 16))
        for match in re.findall(r"functions/([0-9a-f]{8})\.asm", text):
            found.add(int(match, 16))
        addresses = sorted(found)
    addresses += [int(value, 16) for value in args if re.fullmatch(r'0x[0-9a-fA-F]+', value)]
    base, blob, _, _ = FIND.image_text(exe)
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    for address in addresses:
        lines, total = function(MD, address, blob, base)
        header = ('; th11 (jp) %08x  %d instructions, %d bytes  -- canonical disassembly,'
                  ' generated by tools/th-asm-dump.py' % (address, len(lines), total))
        path = os.path.join(OUT, '%08x.asm' % address)
        io.open(path, 'w', encoding='utf-8', newline='').write(
            '\r\n'.join([header] + lines) + '\r\n')
        calls = sum(1 for line in lines if 'CALL 0x00456c10' in line)
        print('  %08x: %4d instructions -> %s (%d scene registrations)'
              % (address, len(lines), path, calls))


main()
